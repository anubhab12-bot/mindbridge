"""Development mock provider.

Produces simple, rule-composed supportive replies so the product can be developed and tested
without credentials. Every result is flagged `is_mock=True`, which the API stores and the web
app shows as "Development mock – not a real AI model". It is refused in production by config.
"""

from __future__ import annotations

import json
import re

from app.providers.base import ProviderResult

_THEMES: list[tuple[str, str, str]] = [
    (
        r"\b(lonely|alone|isolated|no one|nobody)\b",
        "feeling lonely",
        "Would it help to think of one person you could send a short message to today, even just to say hello?",
    ),
    (
        r"\b(anxious|anxiety|worried|panic|nervous|overthinking)\b",
        "feeling anxious",
        "One thing some people find helpful is slow breathing: in for 4 counts, out for 6, a few times. What tends to set the worry off for you?",
    ),
    (
        r"\b(sad|down|low|depressed|empty|crying|cry)\b",
        "feeling low",
        "When you feel like this, is there anything small that has helped even a little before?",
    ),
    (
        r"\b(sleep|insomnia|tired|exhausted|can't sleep)\b",
        "struggling with sleep and tiredness",
        "A wind-down routine without screens for half an hour before bed helps some people. How have your nights been lately?",
    ),
    (
        r"\b(stress|stressed|pressure|exam|work|deadline)\b",
        "under a lot of pressure",
        "Would it help to break what's in front of you into one small next step?",
    ),
    (
        r"\b(angry|frustrated|annoyed|irritated)\b",
        "feeling frustrated",
        "It can help to name exactly what feels unfair. What's been weighing on you most?",
    ),
]


class MockProvider:
    name = "mock"
    model = "development-mock"
    is_mock = True

    async def generate(
        self, *, system: str, messages: list[dict[str, str]], max_tokens: int, temperature: float = 0.4
    ) -> ProviderResult:
        last = messages[-1]["content"] if messages else ""
        text_in = re.sub(r"<<<USER|USER>>>|<<<MESSAGE|MESSAGE>>>", "", last).lower()
        tokens_in = sum(len(m["content"].split()) for m in messages) + len(system.split())

        if "safety classifier" in system:
            reply = json.dumps({"risk_level": "NONE", "signals": []})
        elif system.startswith("Summarise this conversation"):
            reply = "- You shared how you've been feeling recently.\n- You talked through what has been hard.\n- You considered a small next step."
        elif "assist a qualified mental health professional" in system:
            reply = (
                "DRAFT (development mock, not generated by a real AI model)\n"
                "- Main concerns: Not stated in detail.\n- Goals: Not stated.\n"
                "- Considerations for the professional: review the patient's own words before using this draft."
            )
        else:
            theme = next(((t, f) for p, t, f in _THEMES if re.search(p, text_in)), None)
            if theme:
                reply = f"It sounds like you're {theme[0]}, and that can be really hard. Thank you for sharing it here. {theme[1]}"
            else:
                reply = (
                    "Thank you for telling me what's on your mind. I'm here to listen. "
                    "Could you tell me a little more about how you've been feeling?"
                )
            if "hard right now" in system or "feeling unsafe" in system or "very hard" in system:
                reply += " Are you safe right now? If not, please reach out to the crisis support shown in the app or someone you trust."
        return ProviderResult(reply, self.model, tokens_in, len(reply.split()), is_mock=True)

    async def health(self) -> bool:
        return True
