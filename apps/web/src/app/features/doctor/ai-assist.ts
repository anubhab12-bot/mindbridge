import { Component, inject, OnInit, signal } from '@angular/core';
import { FormsModule } from '@angular/forms';
import { RouterLink } from '@angular/router';
import { ClinicalNoteType, DoctorAssistTask } from '@mindbridge/shared-types';
import { ApiService } from '../../core/api/api.service';
import { ApiError, errorMessage } from '../../core/api/api-error';
import { FeatureFlagsService } from '../../core/services/feature-flags.service';
import { ToastService } from '../../core/services/toast.service';
import { humanize } from '../../shared/util/format';

interface DraftResult {
  draftId: string;
  draft: string;
  label: string;
  warnings: string[];
  isMock: boolean;
  usedContext: string[];
}

const PATIENT_TASKS: string[] = [
  DoctorAssistTask.SUMMARIZE_INTAKE,
  DoctorAssistTask.SUMMARIZE_AUTHORIZED_CONVERSATION,
  DoctorAssistTask.ORGANIZE_CONCERNS,
  DoctorAssistTask.SUGGEST_QUESTIONS,
];

@Component({
  selector: 'mb-ai-assist',
  imports: [FormsModule, RouterLink],
  template: `
    <div class="page narrow">
      <header class="page-header">
        <h1>AI drafting</h1>
        <p>Get a first draft to save time. Every draft must be reviewed and edited by you. Nothing is added to a patient record unless you save it.</p>
      </header>
      @if (!flags.enabled('ai.doctor_assist')) {
        <div class="alert alert-warning">AI drafting is turned off at the moment.</div>
      } @else {
        <section class="card">
          <div class="grid-2">
            <div class="field">
              <label for="task">What do you need?</label>
              <select id="task" class="input" [(ngModel)]="task">
                @for (t of tasks; track t) { <option [value]="t">{{ human(t) }}</option> }
              </select>
            </div>
            <div class="field">
              <label for="patient">Patient @if (!needsPatient()) { <span class="muted">(optional)</span> }</label>
              <select id="patient" class="input" [(ngModel)]="patientId">
                <option value="">No patient</option>
                @for (p of patients(); track p.patientId) { <option [value]="p.patientId">{{ p.displayName }}</option> }
              </select>
              <span class="hint">Uses only what this patient has shared with you, and only if they allowed AI drafting.</span>
            </div>
          </div>
          <div class="field">
            <label for="ins">Instructions <span class="muted">(optional)</span></label>
            <textarea id="ins" class="textarea" [(ngModel)]="instructions" maxlength="2000" placeholder="e.g. Keep it brief, use plain language"></textarea>
            <span class="hint">Avoid adding identifying details here.</span>
          </div>
          <button class="btn" type="button" (click)="run()" [disabled]="busy() || (needsPatient() && !patientId)">{{ busy() ? 'Drafting…' : 'Create draft' }}</button>
        </section>

        @if (result(); as r) {
          <section class="card draft" aria-live="polite">
            <div class="row">
              <span class="badge badge-warning">AI draft: requires professional review</span>
              @if (r.isMock) { <span class="badge badge-danger" title="Generated by the development mock, not a real model">Simulated (mock)</span> }
            </div>
            @for (w of r.warnings; track w) { <p class="small muted">{{ w }}</p> }
            @if (r.usedContext.length) { <p class="small muted">Based on: {{ r.usedContext.map(human).join(', ') }}</p> }
            <label for="text" class="label">Edit the draft</label>
            <textarea id="text" class="textarea tall" [(ngModel)]="text"></textarea>
            <div class="row">
              <button class="btn btn-secondary btn-sm" type="button" (click)="copy()">Copy</button>
            </div>
            @if (patientId) {
              <hr class="divider" />
              <h2 class="h3">Save as a draft clinical note</h2>
              <div class="grid-2">
                <div class="field"><label for="nt">Title</label><input id="nt" class="input" [(ngModel)]="noteTitle" maxlength="140" /></div>
                <div class="field">
                  <label for="ntype">Type</label>
                  <select id="ntype" class="input" [(ngModel)]="noteType">
                    @for (t of noteTypes; track t) { <option [value]="t">{{ human(t) }}</option> }
                  </select>
                </div>
              </div>
              <label class="checkbox"><input type="checkbox" [(ngModel)]="reviewed" /><span>I have reviewed and edited this draft and take responsibility for its content.</span></label>
              <button class="btn" type="button" (click)="saveNote()" [disabled]="!reviewed || !noteTitle.trim() || !text.trim()">Save draft note</button>
              @if (savedFor()) { <p class="small">Saved. <a [routerLink]="['/doctor/patients', savedFor()]">Open patient notes</a></p> }
            }
          </section>
        }
      }
    </div>
  `,
  styles: `.narrow { max-width: 860px; } .draft { margin-top: var(--mb-space-4); } .tall { min-height: 260px; margin: 6px 0 10px; } .h3 { font-size: 1.05rem; }`,
})
export class AiAssistPage implements OnInit {
  private readonly api = inject(ApiService);
  private readonly toast = inject(ToastService);
  protected readonly flags = inject(FeatureFlagsService);
  protected readonly tasks = Object.values(DoctorAssistTask);
  protected readonly noteTypes = Object.values(ClinicalNoteType);
  protected readonly human = humanize;
  protected readonly patients = signal<{ patientId: string; displayName: string }[]>([]);
  protected readonly busy = signal(false);
  protected readonly result = signal<DraftResult | null>(null);
  protected readonly savedFor = signal<string | null>(null);
  protected task: string = DoctorAssistTask.DRAFT_NOTE;
  protected patientId = '';
  protected instructions = '';
  protected text = '';
  protected noteTitle = '';
  protected noteType: string = ClinicalNoteType.CONSULTATION_NOTE;
  protected reviewed = false;

  protected needsPatient() {
    return PATIENT_TASKS.includes(this.task);
  }

  ngOnInit() {
    this.api.get<{ patientId: string; displayName: string }[]>('/doctors/me/patients').then((p) => this.patients.set(p), () => undefined);
  }

  async run() {
    this.busy.set(true);
    this.result.set(null);
    this.savedFor.set(null);
    this.reviewed = false;
    try {
      const r = await this.api.post<DraftResult>('/doctors/me/ai-assist', {
        task: this.task,
        patientId: this.patientId || undefined,
        instructions: this.instructions.trim() || undefined,
      });
      this.result.set(r);
      this.text = r.draft;
      this.noteTitle = humanize(this.task);
    } catch (err) {
      this.toast.error(ApiError.from(err).message);
    } finally {
      this.busy.set(false);
    }
  }

  async copy() {
    try {
      await navigator.clipboard.writeText(this.text);
      this.toast.success('Copied.');
    } catch {
      this.toast.error('Copy failed. Select the text and copy it manually.');
    }
  }

  async saveNote() {
    const r = this.result();
    if (!r) return;
    try {
      await this.api.post(`/doctors/me/patients/${this.patientId}/notes`, {
        type: this.noteType,
        title: this.noteTitle.trim(),
        content: this.text,
        fromDraftId: r.draftId,
      });
      this.savedFor.set(this.patientId);
      this.toast.success('Saved as a draft note.');
    } catch (err) {
      this.toast.error(errorMessage(err));
    }
  }
}
